internal fun smartOfflineLocalizationEntries(code: String, base: Map<String, String>): Map<String, String> {
    val translated = smartOfflineTranslations.getValue(code)
    check(translated.size == smartOfflineTranslatedKeys.size) { "Incomplete Smart Offline localization: $code" }
    val nouns = smartOfflineNouns.getValue(code)
    val nounOne = nouns[0]
    val nounOther = nouns[1]
    val nounFew = nouns.getOrElse(2) { nounOther }
    val nounMany = nouns.getOrElse(3) { nounOther }
    val nounTwo = nouns.getOrElse(4) { nounOther }
    val nounZero = nouns.getOrElse(5) { nounOther }
    val countPattern = if (code in setOf("ja", "ko", "zh", "zh-Hant", "th")) "{count}{songs}" else "{count} {songs}"
    return smartOfflineTranslatedKeys.zip(translated).toMap() + mapOf(
        "smartOfflineTitle" to "Smart Offline",
        "smartOfflineMegabytes" to "MB",
        "smartOfflineWifiOnly" to base.getValue("wifiOnly"),
        "smartOfflineWifiOnlySubtitle" to base.getValue("wifiOnlySubtitle"),
        "smartOfflineChargingOnly" to base.getValue("chargingOnly"),
        "smartOfflineChargingOnlySubtitle" to base.getValue("chargingOnlySubtitle"),
        "smartOfflineSave" to base.getValue("save"),
        "smartOfflineUpdatedToday" to base.getValue("collectionUpdatedToday"),
        "smartOfflineSongCountPattern" to countPattern,
        "smartOfflineSongOne" to nounOne,
        "smartOfflineSongOther" to nounOther,
        "smartOfflineSongFew" to nounFew,
        "smartOfflineSongMany" to nounMany,
        "smartOfflineSongTwo" to nounTwo,
        "smartOfflineSongZero" to nounZero
    )
}
