class PlaylistSyncCopy internal constructor(private val texts: Map<PlaylistSyncText, String>) {
    operator fun get(key: PlaylistSyncText): String = texts[key] ?: englishSync.getValue(key)

    fun format(key: PlaylistSyncText, count: Int = 0, name: String = "", time: String = ""): String =
        get(key).replace("{count}", count.toString()).replace("{name}", name).replace("{time}", time)
}

private fun sync(vararg value: String): Map<PlaylistSyncText, String> =
    if (value.size == PlaylistSyncText.entries.size) PlaylistSyncText.entries.zip(value).toMap() else emptyMap()

