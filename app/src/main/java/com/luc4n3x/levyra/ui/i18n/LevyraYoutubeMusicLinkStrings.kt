class YoutubeMusicLinkCopy internal constructor(private val texts: Map<YoutubeMusicLinkText, String>) {
    operator fun get(key: YoutubeMusicLinkText): String = texts[key] ?: englishLink.getValue(key)

    fun format(key: YoutubeMusicLinkText, name: String = "", time: String = ""): String =
        get(key).replace("{name}", name).replace("{time}", time)
}

