internal class LevyraPersonalCollectionStrings(val code: String, private val values: List<String>) {
    val category get() = values[0]
    val title get() = values[1]
    val emptyTitle get() = values[2]
    val emptyDetail get() = values[3]
    val add get() = values[4]
    val importTitle get() = values[5]
    val fromFile get() = values[6]
    val fromFileDetail get() = values[7]
    val fromUrl get() = values[8]
    val fromUrlDetail get() = values[9]
    val urlLabel get() = values[10]
    val usernameLabel get() = values[11]
    val passwordLabel get() = values[12]
    val privacyNote get() = values[13]
    val allowHttp get() = values[14]
    val allowHttpDetail get() = values[15]
    val continueAction get() = values[16]
    val reading get() = values[17]
    val nameLabel get() = values[18]
    val autoRefresh get() = values[22]
    val autoRefreshDetail get() = values[23]
    val importAction get() = values[24]
    val downloadAll get() = values[25]
    val refresh get() = values[26]
    val refreshing get() = values[27]
    val settingsTitle get() = values[28]
    val removeCollection get() = values[29]
    val removeBody get() = values[31]
    val removeDownloads get() = values[32]
    val sourceFile get() = values[36]
    val savedCopy get() = values[37]
    val upToDate get() = values[38]
    val emptyCollection get() = values[40]
    val streamOnly get() = values[41]
    val notAudio get() = values[42]
    val localNetworkTitle get() = values[60]
    val localNetworkDetail get() = values[61]
    val allow get() = values[62]

    fun skipped(count: Int) = values[19].replace("{n}", number(count))
    fun duplicates(count: Int) = values[20].replace("{n}", number(count))
    fun httpTracks(count: Int) = values[21].replace("{n}", number(count))
    fun removeTitle(name: String) = values[30].replace("{name}", isolate(name))
    fun removeDownloadsBody(count: Int) = values[33].replace("{n}", number(count))
    fun offlineCount(count: Int) = values[35].replace("{n}", number(count))
    fun syncSummary(added: Int, removed: Int) =
        values[39].replace("{added}", number(added)).replace("{removed}", number(removed))

    fun error(error: CollectionSyncError): String = values[ERROR_OFFSET + error.ordinal]

    fun updated(timestamp: Long, now: Long = System.currentTimeMillis()): String {
        val zone = ZoneId.systemDefault()
        val locale = Locale.forLanguageTag(code)
        val moment = Instant.ofEpochMilli(timestamp).atZone(zone)
        val today = Instant.ofEpochMilli(now).atZone(zone).toLocalDate()
        val formatted = if (moment.toLocalDate() == today) {
            moment.format(DateTimeFormatter.ofLocalizedTime(FormatStyle.SHORT).withLocale(locale))
        } else {
            moment.format(DateTimeFormatter.ofLocalizedDate(FormatStyle.MEDIUM).withLocale(locale))
        }
        return values[34].replace("{date}", isolate(formatted))
    }

    private fun number(value: Int): String = isolate(String.format(Locale.forLanguageTag(code), "%d", value))

    private fun isolate(value: String): String =
        if (LevyraLanguageCatalog.isRtl(code) && value.isNotBlank()) "\u2068$value\u2069" else value

    companion object {
        const val KEY_COUNT = 63
        const val ERROR_OFFSET = 43
        const val ERROR_COUNT = 17
    }
}

