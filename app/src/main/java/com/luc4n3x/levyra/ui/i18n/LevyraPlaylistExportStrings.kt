package com.luc4n3x.levyra.ui.i18n

internal data class PlaylistExportCopy(
    val action: String,
    val title: String,
    val services: String,
    val files: String,
    val youtubeMusic: String,
    val youtubeConnected: (String) -> String,
    val youtubeSignedOut: String,
    val youtubeNothing: String,
    val m3uLabel: String,
    val m3uDescription: String,
    val csvLabel: String,
    val csvDescription: String,
    val summary: (tracks: Int, ready: Int) -> String,
    val unmatched: (Int) -> String,
    val duplicates: (Int) -> String,
    val sending: (added: Int, total: Int) -> String,
    val sent: (Int) -> String,
    val partial: (added: Int, total: Int) -> String,
    val cancelled: (Int) -> String,
    val networkError: String,
    val signInError: String,
    val serviceError: String,
    val fileSaved: String,
    val fileFailed: String,
    val open: String,
    val cancel: String,
    val retry: String,
    val done: String,
    val back: String,
    val emptyPlaylist: String
)

internal fun playlistExportCopy(code: String): PlaylistExportCopy = when (code.substringBefore('-')) {
    "it" -> PlaylistExportCopy(
        action = "Esporta playlist",
        title = "Esporta playlist",
        services = "Servizi musicali",
        files = "File",
        youtubeMusic = "YouTube Music",
        youtubeConnected = { "Crea una playlist privata su $it" },
        youtubeSignedOut = "Collega YouTube Music da Impostazioni per esportare qui",
        youtubeNothing = "Nessun brano di questa playlist ha un riferimento YouTube Music",
        m3uLabel = "File M3U8",
        m3uDescription = "Lettori, backup e altri servizi. Mantiene titolo, artista e ordine.",
        csvLabel = "File CSV",
        csvDescription = "Fogli di calcolo e strumenti di trasferimento",
        summary = { tracks, ready -> "$tracks brani · $ready pronti per YouTube Music" },
        unmatched = { "$it senza corrispondenza YouTube Music: restano nei file esportati" },
        duplicates = { "$it duplicati verranno aggiunti una sola volta" },
        sending = { added, total -> "Aggiunti $added di $total…" },
        sent = { "Playlist creata su YouTube Music con $it brani" },
        partial = { added, total -> "Esportazione interrotta: $added di $total brani confermati su YouTube Music" },
        cancelled = { "Esportazione annullata dopo $it brani confermati" },
        networkError = "Connessione non riuscita. Riprova tra poco.",
        signInError = "La sessione YouTube Music è scaduta. Accedi di nuovo da Impostazioni.",
        serviceError = "YouTube Music non ha confermato l’operazione. Riprova.",
        fileSaved = "File salvato",
        fileFailed = "Non è stato possibile salvare il file",
        open = "Apri in YouTube Music",
        cancel = "Annulla",
        retry = "Riprova",
        done = "Fine",
        back = "Indietro",
        emptyPlaylist = "La playlist è vuota: aggiungi dei brani per esportarla"
    )
    "ru" -> PlaylistExportCopy(
        action = "Экспорт плейлиста",
        title = "Экспорт плейлиста",
        services = "Музыкальные сервисы",
        files = "Файлы",
        youtubeMusic = "YouTube Music",
        youtubeConnected = { "Создать приватный плейлист в аккаунте $it" },
        youtubeSignedOut = "Подключите YouTube Music в настройках, чтобы экспортировать сюда",
        youtubeNothing = "В этом плейлисте нет треков с идентификатором YouTube Music",
        m3uLabel = "Файл M3U8",
        m3uDescription = "Плееры, резервные копии и другие сервисы. Сохраняет название, исполнителя и порядок.",
        csvLabel = "Файл CSV",
        csvDescription = "Таблицы и сервисы переноса",
        summary = { tracks, ready -> "Треков: $tracks · готово для YouTube Music: $ready" },
        unmatched = { "Без соответствия в YouTube Music: $it. Они останутся в файлах экспорта" },
        duplicates = { "Повторы ($it) будут добавлены один раз" },
        sending = { added, total -> "Добавлено $added из $total…" },
        sent = { "Плейлист создан в YouTube Music, треков: $it" },
        partial = { added, total -> "Экспорт прерван: YouTube Music подтвердил $added из $total" },
        cancelled = { "Экспорт отменён, подтверждено треков: $it" },
        networkError = "Не удалось подключиться. Повторите позже.",
        signInError = "Сессия YouTube Music истекла. Войдите снова в настройках.",
        serviceError = "YouTube Music не подтвердил операцию. Повторите.",
        fileSaved = "Файл сохранён",
        fileFailed = "Не удалось сохранить файл",
        open = "Открыть в YouTube Music",
        cancel = "Отмена",
        retry = "Повторить",
        done = "Готово",
        back = "Назад",
        emptyPlaylist = "Плейлист пуст: добавьте треки, чтобы экспортировать его"
    )
    else -> PlaylistExportCopy(
        action = "Export playlist",
        title = "Export playlist",
        services = "Music services",
        files = "Files",
        youtubeMusic = "YouTube Music",
        youtubeConnected = { "Create a private playlist on $it" },
        youtubeSignedOut = "Connect YouTube Music in Settings to export here",
        youtubeNothing = "No track in this playlist has a YouTube Music reference",
        m3uLabel = "M3U8 file",
        m3uDescription = "Players, backups and other services. Keeps title, artist and order.",
        csvLabel = "CSV file",
        csvDescription = "Spreadsheets and transfer tools",
        summary = { tracks, ready -> "$tracks tracks · $ready ready for YouTube Music" },
        unmatched = { "$it without a YouTube Music match: they stay in exported files" },
        duplicates = { "$it duplicates will be added once" },
        sending = { added, total -> "Added $added of $total…" },
        sent = { "Playlist created on YouTube Music with $it tracks" },
        partial = { added, total -> "Export stopped: YouTube Music confirmed $added of $total tracks" },
        cancelled = { "Export cancelled after $it confirmed tracks" },
        networkError = "Couldn’t connect. Try again shortly.",
        signInError = "Your YouTube Music session expired. Sign in again from Settings.",
        serviceError = "YouTube Music didn’t confirm the request. Try again.",
        fileSaved = "File saved",
        fileFailed = "Couldn’t save the file",
        open = "Open in YouTube Music",
        cancel = "Cancel",
        retry = "Try again",
        done = "Done",
        back = "Back",
        emptyPlaylist = "This playlist is empty: add tracks to export it"
    )
}
