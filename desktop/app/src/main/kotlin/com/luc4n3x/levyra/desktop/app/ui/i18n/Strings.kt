private fun localizedSubscriberLabel(tag: String): String = when (tag.substringBefore('-').lowercase()) {
    "it" -> "iscritti"
    "es" -> "suscriptores"
    "fr" -> "abonnés"
    "de" -> "Abonnenten"
    "pt" -> "inscritos"
    "ru" -> "подписчиков"
    "tr" -> "abone"
    "ar" -> "مشترك"
    "hi" -> "सब्सक्राइबर"
    "ja" -> "登録者"
    "ko" -> "구독자"
    "zh" -> "订阅者"
    else -> "subscribers"
}

